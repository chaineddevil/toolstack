-- 1. AUTHORS TABLE
-- ══════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS authors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  bio TEXT DEFAULT '',
  headshot_url TEXT,
  expertise_areas JSONB DEFAULT '[]'::jsonb,
  social_profiles JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE authors ENABLE ROW LEVEL SECURITY;

-- Public can read authors
CREATE POLICY "authors_public_read" ON authors
  FOR SELECT USING (true);

-- Editors+ can manage authors
CREATE POLICY "authors_admin_insert" ON authors
  FOR INSERT WITH CHECK (
    public.get_user_role() IN ('super_admin', 'manager', 'editor')
  );

CREATE POLICY "authors_admin_update" ON authors
  FOR UPDATE USING (
    public.get_user_role() IN ('super_admin', 'manager', 'editor')
  );

CREATE POLICY "authors_admin_delete" ON authors
  FOR DELETE USING (
    public.get_user_role() = 'super_admin'
  );

GRANT SELECT ON authors TO anon;

